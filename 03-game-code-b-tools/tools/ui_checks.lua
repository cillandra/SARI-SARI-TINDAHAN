-- Purpose: actual rendered station/input smoke checks. API: run(app,fixture). Dependencies: UI coordinates and domain queries; isolated smoke fixtures only.
local W=require('src.ui.widgets')
local L=require('src.ui.layout')
local Cash=require('src.systems.cash')
local Inventory=require('src.systems.inventory')
local Checks={}
local function click(a,x,y)
    a:mousepressed(L.x+x*L.scale,L.y+y*L.scale,1)
end
function Checks.run(a,fixture)
    fixture('counter')
    local card=require('src.ui.order_card')
    a.previewPointer={card.compact.x+20,card.compact.y+20};a:draw()
    assert(a.orderCardHover and not a.ticketOpen,'Rendered compact card must expand on hover')
    click(a,card.compact.x+20,card.compact.y+20)
    assert(a.ticketOpen,'Rendered compact card must pin on click')
    a.previewPointer={card.expanded.x+card.expanded.w-74,card.expanded.y+30};a:draw()
    click(a,a.previewPointer[1],a.previewPointer[2]);a:draw()
    assert(not a.ticketOpen and not a.orderCardHover,'Rendered Close must suppress hover reopening')
    a.previewPointer={-1,-1};a:draw()
    a.previewPointer={card.compact.x+20,card.compact.y+20};a:draw()
    click(a,a.previewPointer[1],a.previewPointer[2]);a:draw();a:keypressed('escape');a:draw()
    assert(not a.ticketOpen and not a.orderCardHover,'Rendered Escape must close a hovered pinned card')
    a.previewPointer={-1,-1}
    print('ORDER CARD CHECK PASS hover, pin, Close, Escape')
    fixture('scale')
    a:draw()
    local before=a:quote().lines[1].actualQuantity
    click(a,154,573)
    assert(a:quote().lines[1].actualQuantity==before+50,'Rendered scoop must add 50 integer grams')
    a:draw()
    click(a,1024,613)
    assert(a:quote().lines[1].actualQuantity==before+51,'Rendered fine adjustment must add one gram')
    a:draw()
    click(a,879,613)
    assert(a:quote().lines[1].actualQuantity==before+50,'Rendered fine adjustment must remove one gram')
    a:keypressed('escape')
    local elapsed=a.state.time.elapsed
    a:update(1)
    assert(a.state.time.elapsed==elapsed,'Station pause must stop simulation')
    a:keypressed('escape')
    a:go('shelves')
    a:draw()
    assert(Inventory.available(a.state,'rice_premium')==0,'Empty cubby fixture must be empty')
    assert(not W.activate(150,180),'Empty cabinet cubby must not register a pick action')
    local cancel=require('src.ui.cabinet_layout').controls.cancel;click(a,cancel.x+cancel.w/2,cancel.y+cancel.h/2)
    assert(not a.state.retail and next(a.state.reservations or {})==nil,'Rendered cancel must release all measured reservations')

    fixture('oil-repack')
    a:draw()
    local oilBefore=a:quote().lines[1].actualQuantity
    click(a,180,573)
    assert(a.pouring,'Rendered hold control must begin pouring')
    a:update(.1)
    assert(a:quote().lines[1].actualQuantity>oilBefore,'Hold must advance the existing integer portion')
    a:keypressed('escape')
    assert(not a.pouring,'Pause must stop held pouring')
    local pausedQuantity=a:quote().lines[1].actualQuantity
    a:update(1)
    assert(a:quote().lines[1].actualQuantity==pausedQuantity,'Paused pouring must not advance')
    a:keypressed('escape')
    a:draw()
    click(a,180,573)
    a:mousereleased(0,0,1)
    assert(not a.pouring and a.pourRemainder==0,'Mouse release must stop and clear fractional tool progress')
    a:draw()
    click(a,180,573)
    a:keyreleased('return')
    assert(not a.pouring,'Keyboard release must stop held pouring')

    fixture('drawer')
    a:draw()
    local cashBefore=Cash.total(a.state)
    a:mousepressed(L.x-1,L.y-1,1)
    assert(not a.change[100],'Letterbox clicks must not reach cash controls')
    local sukli=require('src.ui.sukli_layout')
    local coin=sukli.slots[100]
    click(a,coin.x+coin.w/2,coin.y+coin.h/2)
    assert(a.change[100]==1 and Cash.total(a.state)==cashBefore,'Selecting an actual coin must remain staged')
    a:draw()
    local undo=sukli.controls.undo
    click(a,undo.x+undo.w/2,undo.y+undo.h/2)
    assert(a.change[100]==0 and Cash.total(a.state)==cashBefore,'Rendered undo must return the staged coin')
    a:draw()
    local cancel=sukli.controls.cancel
    click(a,cancel.x+cancel.w/2,cancel.y+cancel.h/2)
    assert(not a.state.retail and Cash.total(a.state)==cashBefore and next(a.state.reservations or {})==nil,'Rendered cancel must return tender and reservations')

    fixture('drawer')
    a:draw()
    local quote=a:quote()
    local change=assert(Cash.plan(a.state,quote.tenderAmount-quote.total,quote.tender))
    for i,d in ipairs(require('data.tuning').denominations) do
        for _=1,change[d] or 0 do
            local r=sukli.slots[d]
            click(a,r.x+r.w/2,r.y+r.h/2)
            a:draw()
        end
    end
    local confirm=sukli.controls.confirm
    click(a,confirm.x+confirm.w/2,confirm.y+confirm.h/2)
    assert(a.view=='counter' and a.state.serviceOutcomes.served==1,'Rendered confirmation must serve once')
    click(a,confirm.x+confirm.w/2,confirm.y+confirm.h/2)
    assert(a.state.serviceOutcomes.served==1,'Repeated click before redraw must not recommit')

    fixture('prepack')
    a:draw()
    local stock=Inventory.available(a.state,'cooking_oil')
    click(a,935,510)
    assert(Inventory.available(a.state,'cooking_oil')==stock and a.packQuantity==150,'Underfilled prep confirmation must retain inventory')
    fixture('counter')
    a:draw()
    click(a,1198,40)
    a:draw()
    local cashAtSave=Cash.total(a.state)
    click(a,540,446)
    assert(a.hasCheckpoint and a.persistence.exists(),'Rendered Save button must create a validated checkpoint')
    a:draw()
    click(a,744,446)
    assert(a.view=='menu','Pause title control must open the menu')
    a:draw()
    a.packQuantity=234
    click(a,220,505)
    assert(a.view=='counter' and a.state.paused and Cash.total(a.state)==cashAtSave and a.packQuantity==0,'Rendered Load must restore paused state and clear transient tools')
    print('SAVE UI CHECK PASS rendered save/menu/load, exact cash and transient cleanup')
    fixture('counter')
    a:draw()
    print('LEGACY STATION UI CHECK PASS scoop/fine controls, hold/release, paused pouring, staged cash, undo/cancel and repeated confirmation')
end
return Checks
